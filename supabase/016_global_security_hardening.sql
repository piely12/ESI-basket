create or replace function public.reject_audit_log_mutation()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if current_user not in ('postgres', 'supabase_admin') then
    -- Preserve the FK's ON DELETE SET NULL action without allowing an
    -- application role to rewrite or erase audit event contents.
    if tg_op = 'UPDATE'
      and old.actor_user_id is not null
      and new.actor_user_id is null
      and (to_jsonb(old) - 'actor_user_id') = (to_jsonb(new) - 'actor_user_id') then
      return new;
    end if;
    raise exception 'audit_logs is append-only';
  end if;
  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;
revoke all on function public.reject_audit_log_mutation() from public, anon, authenticated, service_role;
drop trigger if exists audit_logs_append_only on public.audit_logs;
create trigger audit_logs_append_only
  before update or delete on public.audit_logs
  for each row execute function public.reject_audit_log_mutation();

