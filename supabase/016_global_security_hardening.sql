begin;

create or replace function public.is_current_app_session()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select auth.uid() is not null and exists (
    select 1
    from public.users u
    where u.id = auth.uid()
      and u.is_active = true
      and u.must_change_password = false
      and (
        not exists (
          select 1 from public.staff s
          where s.user_id = auth.uid()
            and s.role in ('coach', 'coach_adjoint', 'admin')
        )
        or exists (
          select 1 from public.active_sessions active_session
          where active_session.user_id = auth.uid()
            and active_session.current_session_id = auth.jwt() ->> 'session_id'
        )
      )
  );
$$;
revoke all on function public.is_current_app_session() from public, anon;
grant execute on function public.is_current_app_session() to authenticated;

-- These predicates are invoked by RLS. Privileged sessions and inactive or
-- first-login accounts must not have a direct PostgREST path around Next.js.
create or replace function public.has_staff_role(allowed_roles text[])
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select public.is_current_app_session() and exists (
    select 1 from public.staff s
    where s.user_id = auth.uid() and s.role = any (allowed_roles)
  );
$$;
revoke all on function public.has_staff_role(text[]) from public;
grant execute on function public.has_staff_role(text[]) to anon, authenticated;

create or replace function public.is_team_staff(target_team_id uuid, allowed_roles text[])
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select public.is_current_app_session() and exists (
    select 1 from public.staff s
    where s.user_id = auth.uid()
      and s.team_id = target_team_id
      and s.role = any (allowed_roles)
  );
$$;
revoke all on function public.is_team_staff(uuid, text[]) from public, anon;
grant execute on function public.is_team_staff(uuid, text[]) to authenticated;

-- Serialize per-user OTP issuance and per-key rate checks to close concurrent
-- count-then-insert races. The opaque key is generated by the server.
create or replace function public.consume_rate_limit(
  p_key text, p_limit integer, p_window_seconds integer
)
returns table (allowed boolean, retry_after_seconds integer)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_count integer;
  v_oldest timestamptz;
begin
  if p_key is null or char_length(p_key) <> 64
    or p_limit < 1 or p_window_seconds < 1 or p_window_seconds > 86400 then
    raise exception 'Invalid rate limit parameters';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_key, 0));
  select count(*)::integer, min(rl.created_at)
    into v_count, v_oldest
  from public.rate_limits rl
  where rl.key = p_key
    and rl.created_at >= now() - make_interval(secs => p_window_seconds);

  if v_count >= p_limit then
    return query select false, greatest(1, ceil(
      extract(epoch from (v_oldest + make_interval(secs => p_window_seconds) - now()))
    )::integer);
    return;
  end if;

  insert into public.rate_limits (key) values (p_key);
  return query select true, 0;
end;
$$;
revoke all on function public.consume_rate_limit(text, integer, integer) from public, anon, authenticated;
grant execute on function public.consume_rate_limit(text, integer, integer) to service_role;

create or replace function public.issue_recovery_otp(
  p_user_id uuid, p_code_hash text, p_expires_at timestamptz, p_max_attempts integer
)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_otp_id uuid;
begin
  if p_code_hash is null or char_length(p_code_hash) <> 64
    or p_max_attempts < 1 or p_max_attempts > 10
    or p_expires_at <= now() or p_expires_at > now() + interval '10 minutes' then
    raise exception 'Invalid recovery OTP parameters';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_user_id::text, 0));
  update public.otp_codes
    set used_at = now()
    where user_id = p_user_id and used_at is null;

  insert into public.otp_codes (user_id, code_hash, expires_at, max_attempts)
  values (p_user_id, p_code_hash, p_expires_at, p_max_attempts)
  returning id into v_otp_id;
  return v_otp_id;
end;
$$;
revoke all on function public.issue_recovery_otp(uuid, text, timestamptz, integer) from public, anon, authenticated;
grant execute on function public.issue_recovery_otp(uuid, text, timestamptz, integer) to service_role;

